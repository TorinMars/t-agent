// Node file sync: the current engine has its own master/slave role and file list.
const FileSyncUI = (() => {
  const $ = id => document.getElementById(id);
  const escapeHtml = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
  let endpoint = '/api/file-sync', active = false, timer = null, generation = 0, state = null, blocked = null;
  const errorText = error => {
    let code = error.message;
    try { code = JSON.parse(code).error || code; } catch {}
    return ({ SYNC_NOT_MASTER: 'Only the master can edit the file list', SYNC_MASTER_NOT_FOUND: 'Master connection not found',
      SYNC_PATH_INVALID: 'Enter a path under the home directory or an absolute path', SYNC_PATH_DUPLICATE: 'This local path is already used by another synced file',
      SYNC_CONFLICT: 'File version conflict. Check both sides', SYNC_FILE_INVALID: 'The file is not a regular file or exceeds 1 MB',
      SYNC_CONTENT_INVALID: 'Invalid file content', REMOTE_HTTP_404: 'The target node is too old. Please update it first',
      REMOTE_TIMEOUT: 'Timed out connecting to the peer', REMOTE_CONNECTION_FAILED: 'Cannot reach the master. Check the address in the connection string and this machine’s network',
      SYNC_PAIRING_CODE_INVALID: 'Invalid pairing code format; it should look like TA-XXXX-XXXX-XXXX', SYNC_MASTER_URL_INVALID: 'Invalid address',
      SYNC_CONNECTION_STRING_INVALID: 'Invalid connection string. Copy the full text generated by the master', SYNC_NOT_CHILD: 'Only a slave can do this', SYNC_ROLE_INVALID: 'Invalid role',
      PAIRING_RATE_LIMITED: 'Too many attempts. Please try again later',
      PAIRING_CODE_INVALID_OR_EXPIRED: 'The connection string has expired or was already used (valid for 10 minutes, single use). Generate a new one on the master', PAIRING_CODE_ALREADY_USED: 'The pairing code was already used. Generate a new one',
      REMOTE_HTTP_429: 'Too many attempts. Please try again later', SYNC_SELF_CONNECTION: 'A node cannot join itself' })[code] || code;
  };
  function message(text) { $('file-sync-status').textContent = text || ''; }
  async function refresh() {
    if (blocked) { message(blocked); return; }
    const current = ++generation;
    try {
      const next = await API.get(endpoint);
      if (current !== generation) return;
      state = next;
      const master = next.role === 'master';
      const waiting = !master && next.master_id == null && !next.master_url;
      $('file-sync-role-select').value = master ? 'master' : 'slave';
      $('file-sync-invite').hidden = !master;
      $('file-sync-disconnect').hidden = master || waiting;
      $('file-sync-run').hidden = waiting;
      $('file-sync-master-actions').hidden = !master;
      $('file-sync-role').textContent = master ? 'Current role: master'
        : waiting ? 'Current role: slave (not linked to a master yet)' : `Current role: slave (master: ${next.master_url || `connection #${next.master_id}`})`;
      $('file-sync-join-box').hidden = !waiting;
      $('file-sync-children').hidden = !master;
      const children = Array.isArray(next.children) ? next.children : [];
      $('file-sync-children-hint').textContent = !Array.isArray(next.children)
        ? 'This engine must be upgraded before it can list slaves.'
        : children.length ? `${children.length} slave(s) registered; a slave shows as offline after about 15 seconds without a heartbeat.` : 'No slaves registered yet. Click “Generate connection string” and copy it to a slave to connect.';
      $('file-sync-children-table').hidden = !children.length;
      const childrenBody = $('file-sync-children-body');
      childrenBody.replaceChildren();
      for (const child of children) {
        const tr = document.createElement('tr');
        const values = [`${child.name} · ${child.id.slice(0, 8)}`, child.online ? 'Online' : 'Offline',
          child.last_sync_at ? new Date(child.last_sync_at).toLocaleString() : 'Not synced yet',
          child.last_seen_at ? new Date(child.last_seen_at).toLocaleString() : 'Unknown',
          child.error || '—'];
        values.forEach((value, index) => {
          const td = document.createElement('td');
          td.textContent = value;
          if (index === 0) td.title = child.id;
          tr.append(td);
        });
        childrenBody.append(tr);
      }
      const body = $('file-sync-body');
      body.replaceChildren();
      for (const file of next.files) {
        const tr = document.createElement('tr');
        for (const value of [file.path, file.local_path, file.path_required ? 'Local path required' : file.backup ? `Exists · original backed up: ${file.backup}` : file.exists ? 'Exists' : 'Missing', String(file.version)]) {
          const td = document.createElement('td'); td.textContent = value; tr.append(td);
        }
        const action = document.createElement('td');
        if (master) {
          const remove = document.createElement('button'); remove.className = 'btn-logout'; remove.textContent = 'Remove';
          remove.addEventListener('click', async () => {
            if (!confirm(`Remove ${file.path} from the sync list? The local file is not deleted.`)) return;
            await run(() => API.put(`${endpoint}/files`, { files: state.files.filter(item => item.path !== file.path).map(item => item.path) }));
          });
          action.append(remove);
        } else {
          const edit = document.createElement('button'); edit.className = 'btn-logout'; edit.textContent = 'Change local path';
          edit.addEventListener('click', () => {
            Modal.show('Change local path', `<label>Local path<input id="sync-local-path" type="text" autocomplete="off"></label><div class="form-hint">Master path: ${escapeHtml(file.path)}. Leave empty to restore the default path; the default on this node is ${escapeHtml(file.default_path)}. After changing the path, the first download backs up differing content already at the target.</div><div class="form-actions"><button type="button" class="btn-submit" id="sync-local-save">Save</button></div>`);
            const input = $('sync-local-path');
            input.value = file.path_override || file.default_path;
            $('sync-local-save').addEventListener('click', async () => {
              const value = input.value.trim();
              Modal.hide();
              await run(() => API.put(`${endpoint}/path`, { path: file.path, local_path: value === file.default_path ? '' : value }));
            });
          });
          action.append(edit);
        }
        tr.append(action); body.append(tr);
      }
      message(next.error ? `Sync error: ${next.error}` : next.registration_error ? `Registering this node on the master failed: ${next.registration_error}` : next.last_sync_at ? `Last check: ${new Date(next.last_sync_at).toLocaleString()}` : 'Waiting for the first check');
      const conflict = next.error?.startsWith('SYNC_CONFLICT:') ? next.error.slice('SYNC_CONFLICT:'.length) : null;
      if (conflict) {
        const button = document.createElement('button');
        button.type = 'button'; button.className = 'btn-logout';
        button.textContent = 'Back up the conflicting local file and use the master version';
        button.addEventListener('click', () => {
          if (confirm(`This backs up the local content of ${conflict}, then uses the master version. Continue?`)) {
            run(() => API.post(`${endpoint}/resolve`, { path: conflict }));
          }
        });
        $('file-sync-status').append(' ', button);
      }
    } catch (error) { if (current === generation) message(`Read failed: ${errorText(error)}`); }
  }
  async function run(action) {
    try { message('Working…'); await action(); await refresh(); }
    catch (error) { message(`Operation failed: ${errorText(error)}`); }
  }
  function setEngine({ base, label, unavailable }) {
    endpoint = base;
    blocked = unavailable;
    $('file-sync-engine').textContent = `Current engine: ${label}${unavailable ? ` · ${unavailable}` : ''}`;
    for (const id of ['file-sync-role-select', 'file-sync-invite', 'file-sync-connect', 'file-sync-disconnect', 'file-sync-run', 'file-sync-add']) {
      $(id).disabled = Boolean(unavailable);
    }
    generation++;
    if (active) { if (unavailable) { message(unavailable); $('file-sync-body').replaceChildren(); } else refresh(); }
  }
  function setActive(value) {
    active = value;
    clearInterval(timer);
    if (active) { refresh(); timer = setInterval(refresh, 5000); }
  }
  $('file-sync-run').addEventListener('click', () => run(() => API.post(`${endpoint}/run`, {})));
  $('file-sync-role-select').addEventListener('change', async event => {
    const role = event.target.value;
    const text = role === 'slave'
      ? 'Switch to slave? This node’s sync list is cleared (local files are kept); then paste the master’s connection string to connect.'
      : 'Switch to master? The link to the current master is removed and the sync list is cleared (local files are kept).';
    if (!confirm(text)) { refresh(); return; }
    await run(() => API.put(`${endpoint}/role`, { role }));
  });
  async function copyText(input, okText) {
    input.select();
    try { await navigator.clipboard.writeText(input.value); message(okText); }
    catch { message('Copy the selected content manually'); }
  }
  $('file-sync-invite').addEventListener('click', () => {
    Modal.show('Generate connection string', `<label>Connection string<textarea class="form-input" id="sync-invite-string" rows="4" readonly spellcheck="false"></textarea></label><div class="form-hint" id="sync-invite-hint"></div><div class="form-actions"><button type="button" class="btn-submit" id="sync-invite-copy">Copy</button></div><details class="form-advanced"><summary>Advanced: change the master address</summary><label>Slaves use this to connect<input id="sync-invite-url" type="text" placeholder="Defaults to the address you are using now, e.g. https://master.example.com" autocomplete="off"></label><div class="form-actions"><button type="button" class="btn-cancel" id="sync-invite-make">Regenerate with this address</button></div></details><div class="form-hint">The string contains a pairing code valid for 10 minutes and single use. Generate one per slave, send it only to your own server, and use an HTTPS address across the public internet.</div>`);
    const make = async () => {
      const master_url = $('sync-invite-url').value.trim();
      try {
        const invite = await API.post(`${endpoint}/invite`, master_url ? { master_url } : {});
        $('sync-invite-string').value = invite.connection_string;
        $('sync-invite-hint').textContent = `Expires at ${new Date(invite.expires_at).toLocaleTimeString()}, single use.`;
        $('sync-invite-string').select();
      } catch (error) { message(`Generation failed: ${errorText(error)}`); }
    };
    $('sync-invite-make').addEventListener('click', make);
    $('sync-invite-copy').addEventListener('click', () => copyText($('sync-invite-string'), 'Connection string copied'));
    // A local master uses the address the browser is currently using; a remote engine builds it from the address the request arrived at.
    if (endpoint === '/api/file-sync') $('sync-invite-url').value = location.origin;
    make();
  });
  $('file-sync-connect').addEventListener('click', async () => {
    const connection_string = $('file-sync-join-input').value.trim();
    if (!connection_string) return;
    await run(() => API.post(`${endpoint}/join`, { connection_string }));
    $('file-sync-join-input').value = '';
  });
  $('file-sync-disconnect').addEventListener('click', () => {
    if (confirm('Unlink from the master? The sync list is cleared and local files are kept; you can paste a new connection string to reconnect later.')) run(() => API.post(`${endpoint}/unpair`, {}));
  });
  $('file-sync-add').addEventListener('click', () => {
    Modal.show('Add sync file', `<label>File path<input id="sync-new-path" type="text" placeholder="~/.claude/settings.json" autocomplete="off"></label><div class="form-hint">Home-directory paths resolve to each node’s own home directory. Absolute paths are used as-is on every node.</div><div class="form-actions"><button type="button" class="btn-submit" id="sync-new-save">Add</button></div>`);
    $('sync-new-save').addEventListener('click', async () => {
      const path = $('sync-new-path').value.trim();
      if (!path) return;
      Modal.hide();
      await run(() => API.put(`${endpoint}/files`, { files: [...state.files.map(file => file.path), path] }));
    });
  });
  return { setEngine, setActive };
})();
